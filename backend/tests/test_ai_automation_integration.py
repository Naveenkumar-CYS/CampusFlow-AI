# TEST 2 -- Lower risk, REAL model, no fabricated HIGH-risk behavior
# =======================================================================


def test_lower_risk_does_not_fabricate_high_risk_behavior(use_real_model):
    recording_email = RecordingEmailProvider()
    notification_service = NotificationService(email_provider=recording_email, sms_provider=MockSMSProvider())
    consumer, _ = make_consumer(notification_service)

    # Attendance still has to be < 75 for the existing deterministic
    # rule to fire at all -- but everything else here sits in the
    # synthetic LOW-risk cluster (strong marks, no missed assignments,
    # no fee overdue), so the real model's *overall* assessment should
    # come back clearly lower than the HIGH case above, and must never
    # be reported as HIGH.
    event = attendance_event(
        aggregate_id="ATT-AI-LOWER",
        attendance_percentage=70,
        average_marks=85,
        missed_assignments=0,
        fee_overdue_indicator=False,
    )
    result = consumer.consume(event)

    assert result.status == "workflow_triggered"
    assert result.workflow_run.status == "success"

    direct = risk_module.predict_risk(StudentRiskFeaturesInput(
        attendance_percentage=70, average_marks=85, missed_assignments=0, fee_overdue_indicator=False,
    ))
    assert direct.risk_level != "HIGH"

    high_direct = risk_module.predict_risk(StudentRiskFeaturesInput(
        attendance_percentage=55, average_marks=42, missed_assignments=6, fee_overdue_indicator=True,
    ))
    assert direct.risk_score < high_direct.risk_score

    body = recording_email.sent[0]["body"]
    assert "risk assessment: HIGH" not in body


