def test_ai_failure_does_not_fabricate_a_result(use_missing_model):
    """No trained model artifact available -- the REAL failure path in
    app.analytics.model.load_model / app.analytics.advisory.get_ai_advisory,
    not a mock raising an exception."""
    recording_email = RecordingEmailProvider()
    notification_service = NotificationService(email_provider=recording_email, sms_provider=MockSMSProvider())
    consumer, _ = make_consumer(notification_service)

    event = attendance_event(aggregate_id="ATT-AI-FAIL", attendance_percentage=60)

    advisory_result = ai_context_module.for_event(event)
    assert advisory_result is not None
    assert advisory_result.ai_available is False
    assert advisory_result.risk_score is None
    assert advisory_result.risk_level is None

    result = consumer.consume(event)

    # Deterministic pipeline (rule -> workflow -> notify) is unaffected
    # by the AI being unavailable -- this project's explicit,
    # architecturally-documented choice (AI is advisory, never a
    # dependency of the deterministic path) per Part 10/Part 9.
    assert result.status == "workflow_triggered"
    assert result.workflow_run.status == "success"

    body = recording_email.sent[0]["body"]
    # Must say AI was unavailable, and must NOT claim any risk level --
    # i.e. never silently report a fabricated success.
    assert "unavailable" in body.lower()
    assert "risk assessment: HIGH" not in body
    assert "risk assessment: MEDIUM" not in body
    assert "risk assessment: LOW" not in body


