# TEST 5 -- Duplicate event: no duplicate AI processing/workflow/notify
# =======================================================================


def test_duplicate_event_id_does_not_duplicate_ai_or_workflow_execution(use_real_model, monkeypatch):
    calls = {"n": 0}
    real_for_event = ai_context_module.for_event

    def _counting_for_event(event):
        calls["n"] += 1
        return real_for_event(event)

    monkeypatch.setattr(ai_context_module, "for_event", _counting_for_event)
    # WorkflowEngine imported ai_context as a module and calls
    # ai_context.for_event(...), so patching the module attribute above
    # is picked up without touching workflows.py.

    recording_email = RecordingEmailProvider()
    notification_service = NotificationService(email_provider=recording_email, sms_provider=MockSMSProvider())
    consumer, store = make_consumer(notification_service)

    event = attendance_event(
        aggregate_id="ATT-AI-DUP",
        attendance_percentage=55,
        average_marks=42,
        missed_assignments=6,
        fee_overdue_indicator=True,
    )

    first = consumer.consume(event)
    second = consumer.consume(event)  # same event_id, sent twice

    assert first.status == "workflow_triggered"
    assert second.status == "skipped_duplicate"
    assert second.workflow_run is None

    # AI advisory (and therefore the model) was invoked exactly once --
    # the existing Stage 2 idempotency check short-circuits before the
    # rule/workflow/AI path is ever reached a second time.
    assert calls["n"] == 1
    # Exactly one notification, one email, one SMS -- no duplicates.
    assert len(recording_email.sent) == 1


def test_duplicate_event_id_via_event_bus_does_not_duplicate_notification(use_real_model):
    """Same guarantee, this time proven through the real Event Bus
    transport (a producer retry re-publishing the same event_id)."""
    recording_email = RecordingEmailProvider()
    notification_service = NotificationService(email_provider=recording_email, sms_provider=MockSMSProvider())
    store = InMemoryExecutionStore()
    consumer = EventConsumer(RuleEngine(), WorkflowEngine(store, notification_service=notification_service), store)
    bus = InMemoryEventBus()
    runner = EventBusRunner(bus, consumer)

    event = attendance_event(aggregate_id="ATT-AI-DUP-BUS", attendance_percentage=50)
    bus.publish(event)
    bus.publish(event)  # same event_id republished

    results = runner.run_once(count=10)

    assert len(results) == 2
    statuses = [r.status for r in results]
    assert statuses.count("workflow_triggered") == 1
    assert statuses.count("skipped_duplicate") == 1
    assert len(recording_email.sent) == 1


