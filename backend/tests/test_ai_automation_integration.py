# TEST 1 -- High risk, full real chain, driven through the Event Bus
# =======================================================================


def test_high_risk_flows_event_to_notification_through_real_chain(use_real_model):
    """Event -> Event Bus -> Event Processor -> Rule Engine -> REAL AI
    Advisory Service (REAL Stage 5A model) -> Workflow Engine -> Action
    Executor -> Notification Service, proven through the real
    InMemoryEventBus + EventBusRunner transport, not just a direct
    consumer.consume() call."""
    recording_email = RecordingEmailProvider()
    notification_service = NotificationService(email_provider=recording_email, sms_provider=MockSMSProvider())

    store = InMemoryExecutionStore()
    consumer = EventConsumer(RuleEngine(), WorkflowEngine(store, notification_service=notification_service), store)
    bus = InMemoryEventBus()
    runner = EventBusRunner(bus, consumer)

    # Centre of the synthetic HIGH-risk training cluster (see module
    # docstring) -- attendance also < 75 so the existing deterministic
    # rule (RULE-001) fires and the workflow actually runs.
    event = attendance_event(
        aggregate_id="ATT-AI-HIGH",
        attendance_percentage=55,
        average_marks=42,
        missed_assignments=6,
        fee_overdue_indicator=True,
        contact_email="student@example.edu",
    )
    bus.publish(event)

    results = runner.run_once()

    assert len(results) == 1
    result = results[0]
    assert result.status == "workflow_triggered"
    assert result.workflow_run.workflow_id == "attendance_warning"
    assert result.workflow_run.status == "success"
    action_names = [a.action for a in result.workflow_run.action_results]
    assert action_names == ["create_notification", "send_email", "send_sms", "record_execution"]
    assert all(a.status == "success" for a in result.workflow_run.action_results)

    # The REAL model, not a hardcoded value, produced HIGH here.
    direct = risk_module.predict_risk(StudentRiskFeaturesInput(
        attendance_percentage=55, average_marks=42, missed_assignments=6, fee_overdue_indicator=True,
    ))
    assert direct.risk_level == "HIGH"

    # And that REAL result reached the notification the student/staff
    # actually received -- proving the AI result flowed all the way
    # downstream through the existing workflow/action context, not just
    # that the model predicted HIGH in isolation.
    assert len(recording_email.sent) == 1
    body = recording_email.sent[0]["body"]
    assert "Advisory only" in body
    assert "HIGH" in body
    assert "not an automatic decision" in body


