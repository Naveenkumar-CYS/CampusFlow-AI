"""
Stage 5B-2: AI Advisory <-> Automation pipeline integration tests.

    CanonicalEvent (attendance.marked)
              |
    Event Bus (InMemoryEventBus, same transport contract as Redis --
              see app/events/bus.py)
              |
    EventBusRunner -> EventConsumer (Event Processor)
              |
        RuleEngine (existing, deterministic -- attendance % < 75)
              |
        WorkflowEngine._execute_steps()
              |          \\
              |           `-- ai_context.for_event() -> REAL Stage 5B-1
              |                app.analytics.advisory.get_ai_advisory()
              |                -> REAL Stage 5A trained model
              |
        ActionExecutor -> create_notification / send_email / send_sms
              |
        NotificationService (mock email/SMS providers -- external
              network is what's mocked here, never the AI/automation
              chain itself)

Model lifecycle mirrors tests/test_ai_advisory.py exactly: train once
into a throwaway artifact path per test session and point risk.py's
cached loader at it, so predictions come from a real, freshly-trained
Stage 5A RandomForestClassifier -- nothing about the model itself is
mocked in the success-path tests. Only test_ai_failure_* deliberately
points at a missing artifact to exercise the real "model not trained"
failure path end-to-end.

Feature values for the HIGH/lower-risk cases below were chosen to sit
at (or very near) the centres of the synthetic HIGH/LOW training
clusters generated by app.analytics.training.generate_training_dataset
(see that module's _CLASS_PARAMS) -- they are not hand-picked to force
a particular output; they simply ask the real model about a clearly
at-risk vs. clearly not-at-risk student profile and check what it
actually says.
"""
