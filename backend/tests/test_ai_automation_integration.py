class RecordingEmailProvider:
    """Test double standing in for the real SMTP provider -- exactly the
    kind of "external SMTP/SMS" mocking Part 12 explicitly allows. Never
    touches the network; records what was actually sent so tests can
    assert on notification content without changing any production
    interface."""

    name = "recording_email"

    def __init__(self) -> None:
        self.sent: list[dict] = []

    def send(self, *, to: str, subject: str, body: str) -> ProviderResult:
        self.sent.append({"to": to, "subject": subject, "body": body})
        return ProviderResult(status="sent", provider=self.name, channel="email", provider_message_id="rec-1")


def make_consumer(notification_service: NotificationService | None = None):
    store = InMemoryExecutionStore()
    rule_engine = RuleEngine()
    workflow_engine = WorkflowEngine(store, notification_service=notification_service)
    return EventConsumer(rule_engine, workflow_engine, store), store


def attendance_event(**data_overrides) -> CanonicalEvent:
    """Build a real attendance.marked CanonicalEvent (the existing
    envelope, app/automation/events.py) with extra AI-relevant fields
    folded into `data` -- exactly the fields ai_context.py reads, using
    the same key names StudentRiskFeaturesInput already defines."""
    event = make_attendance_marked_event(
        attendance_percentage=data_overrides.pop("attendance_percentage", 65),
        aggregate_id=data_overrides.pop("aggregate_id", "ATT-AI-001"),
    )
    merged_data = dict(event.data)
    merged_data.update(data_overrides)
    return event.model_copy(update={"data": merged_data})


